#!/usr/bin/env python3
"""Generate narration clips with Kokoro (local, free) from narration.json.

    python3 voice.py <project> en                 # voice from video.json (default am_michael)
    python3 voice.py <project> hinglish --voice hm_omega --lang hi
    python3 voice.py <project> en --only 3        # one scene

ElevenLabs clips are generated by the agent through the ElevenLabs MCP tools (see SKILL.md) and
saved as <track audio dir>/s<i>.mp3; this script is only for Kokoro.
Needs: pip install kokoro-onnx soundfile (model downloads from github.com on first run).
"""
import argparse
import os
import subprocess
import tempfile

from common import hyperframes_cmd, load_project, narration, need


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("track")
    ap.add_argument("--voice")
    ap.add_argument("--lang")
    ap.add_argument("--speed", type=float)
    ap.add_argument("--only", type=int)
    a = ap.parse_args()
    need("ffmpeg")

    project, cfg = load_project(a.project)
    texts = narration(project)[a.track]
    vcfg = cfg.get("voice", {}).get(a.track, {})
    voice = a.voice or (vcfg.get("voice") if vcfg.get("engine") == "kokoro" else None) or "am_michael"
    out_dir = os.path.join(project, cfg["tracks"][a.track]["audio"])
    os.makedirs(out_dir, exist_ok=True)

    for i, text in enumerate(texts, 1):
        if a.only and i != a.only:
            continue
        if not text.strip():
            print(f"s{i}: empty narration, skipped")
            continue
        with tempfile.TemporaryDirectory() as tmp:
            txt, wav = os.path.join(tmp, "t.txt"), os.path.join(tmp, "s.wav")
            with open(txt, "w") as f:
                f.write(text)
            cmd = hyperframes_cmd() + ["tts", txt, "-v", voice, "-s", str(a.speed or cfg.get("speed", 1.0)), "-o", wav, "--json"]
            if a.lang:
                cmd += ["-l", a.lang]
            subprocess.run(cmd, check=True, cwd=project, stdout=subprocess.DEVNULL)
            mp3 = os.path.join(out_dir, f"s{i}.mp3")
            # trim leading/trailing silence, 48 kHz mono mp3
            subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", wav, "-af",
                            "silenceremove=start_periods=1:start_threshold=-50dB,areverse,"
                            "silenceremove=start_periods=1:start_threshold=-50dB,areverse",
                            "-ar", "48000", "-ac", "1", "-b:a", "160k", mp3], check=True)
        print(f"s{i}: {mp3}")


if __name__ == "__main__":
    main()
