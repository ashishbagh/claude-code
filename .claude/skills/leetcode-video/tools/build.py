#!/usr/bin/env python3
"""Write the root composition(s) from video.json + narration clip lengths.

    python3 build.py <project> en          # writes index.html for the English track
    python3 build.py <project> hinglish    # rewrites index.html for Hinglish (render in between)

HyperFrames allows one root composition, so index.html always holds exactly one track.

Scene i lasts len(clip i) + pad (the last scene also + "outro_hold", default 3 s, for the subscribe
call-out). Each scene host gets data-variable-values {"T": <scene length>, "S": <narration length>} so
the scene file can time its tweens as fractions of T or S (same code for every language).
SFX cues: {"scene": id, "at": fraction of T  |  "sec": seconds into the scene, "sound": name,
"volume": 0.35}; each sound is shifted so its loudest point lands one frame after the cue.
Also writes timing_<track>.json (scene starts/lengths) for insta.py.
"""
import argparse
import array
import json
import math
import os
import subprocess

from common import clip_path, duration, load_project

FPS = 30

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=1920, height=1080" />
<title>LeetCode {number} – {title}</title>
<link rel="stylesheet" href="assets/lc.css" />
<script src="assets/lib/gsap.min.js"></script>
<script src="assets/lib/three.min.js"></script>
<script src="assets/lib/lc.js"></script>
{scripts}<style>
  html, body {{ width: 1920px; height: 1080px; overflow: hidden; background: #0d1121; }}
  #bg {{ position: absolute; inset: 0; background: radial-gradient(ellipse at 50% 40%, #151c36 0%, #0d1121 70%); }}
</style>
</head>
<body>
<!-- GENERATED by build.py from video.json – edit scenes in compositions/, timing in video.json -->
<div id="root" data-composition-id="main" data-start="0" data-duration="{total:.3f}" data-width="1920" data-height="1080">
  <div id="bg"></div>
"""

TAIL = """</div>
<script>
  window.__timelines = window.__timelines || {};
  window.__timelines["main"] = gsap.timeline({ paused: true });
</script>
</body>
</html>
"""


def peak_offset(path):
    """Seconds from the file start to its loudest sample (8 kHz mono analysis)."""
    raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", "8000",
                                   "-f", "s16le", "-"])
    a = array.array("h")
    a.frombytes(raw[: len(raw) // 2 * 2])
    if not a:
        return 0.0
    i = max(range(len(a)), key=lambda k: abs(a[k]))
    return i / 8000.0


def build_track(project, cfg, track):
    t = cfg["tracks"][track]
    pad = cfg.get("pad", 0.6)
    scenes = cfg["scenes"]
    clips = [clip_path(project, t["audio"], i) for i in range(1, len(scenes) + 1)]
    if not all(clips):
        missing = [f"s{i}" for i, c in enumerate(clips, 1) if not c]
        print(f"[{track}] skipped – missing clips {missing} in {t['audio']}")
        return None
    lens = [round(duration(c) + pad, 3) for c in clips]
    hold = cfg.get("outro_hold", 3.0)          # extra seconds on the last slide for the subscribe call-out
    lens[-1] = round(lens[-1] + hold, 3)
    starts = [round(sum(lens[:i]), 3) for i in range(len(lens))]
    total = round(sum(lens), 3)
    pos = {sid: (starts[i], lens[i]) for i, sid in enumerate(scenes)}
    speech = [round(duration(c), 3) for c in clips]  # narration length per scene (variable "S")

    scripts = "".join(f'<script src="{s}"></script>\n' for s in cfg.get("scripts", []))
    html = [HEAD.format(number=cfg["number"], title=cfg["title"], total=total, scripts=scripts)]
    for i, sid in enumerate(scenes):
        s, T = pos[sid]
        html.append(
            f'  <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html"'
            f' data-start="{s}" data-duration="{T}" data-track-index="0" data-track-kind="graphics"'
            f' data-width="1920" data-height="1080" data-variable-values=\'{{"T":{T},"S":{speech[i]}}}\'></div>\n')
    for i, c in enumerate(clips):
        rel = os.path.relpath(c, project)
        html.append(f'  <audio id="vo-{track}-{i + 1}" class="clip" src="{rel}" data-start="{starts[i]}"'
                    f' data-duration="{math.floor((speech[i] - 0.06) * 100) / 100}" data-track-index="1" data-volume="1"></audio>\n')

    # sound effects, peak-aligned, greedy lanes from 2 upwards
    lanes_end = []
    peaks = {}
    for n, cue in enumerate(cfg.get("sfx", [])):
        if cue["scene"] not in pos:
            continue
        s, T = pos[cue["scene"]]
        at = s + (cue["sec"] if "sec" in cue else cue.get("at", 0) * T)
        f = os.path.join(project, "assets", "sfx", f"{cue['sound']}.mp3")
        if not os.path.exists(f):
            print(f"[{track}] sfx {cue['sound']} missing – run sfx.py")
            continue
        if f not in peaks:
            peaks[f] = (peak_offset(f), duration(f))
        pk, dur = peaks[f]
        start = max(0.0, round(at + 1 / FPS - pk, 3))
        lane = next((k for k, e in enumerate(lanes_end) if e <= start), None)
        if lane is None:
            lanes_end.append(0)
            lane = len(lanes_end) - 1
        lanes_end[lane] = start + dur
        html.append(f'  <audio id="sfx-{n + 1}" class="clip" src="assets/sfx/{cue["sound"]}.mp3"'
                    f' data-start="{start}" data-duration="{round(dur, 3)}" data-track-index="{2 + lane}"'
                    f' data-volume="{cue.get("volume", 0.35)}"></audio>\n')

    music = cfg.get("music")
    if music:
        html.append(f'  <audio id="music" class="clip" src="{music["file"]}" data-start="0"'
                    f' data-duration="{total}" data-track-index="{2 + max(1, len(lanes_end))}"'
                    f' data-volume="{music.get("volume", 0.14)}" data-fade-in="1" data-fade-out="2"></audio>\n')
    html.append(TAIL)

    with open(os.path.join(project, "index.html"), "w") as f:
        f.write("".join(html))
    with open(os.path.join(project, f"timing_{track}.json"), "w") as f:
        json.dump({"scenes": [{"id": sid, "start": starts[i], "length": lens[i],
                               "speech": speech[i]} for i, sid in enumerate(scenes)],
                   "total": total}, f, indent=1)
    print(f"[{track}] index.html: {len(scenes)} scenes, {total:.1f}s -> render to {t['out']}")
    return total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("track", nargs="?", default="en")
    a = ap.parse_args()
    project, cfg = load_project(a.project)
    if build_track(project, cfg, a.track) is None:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
