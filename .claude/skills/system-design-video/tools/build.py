#!/usr/bin/env python3
"""Write the root composition(s) from video.json + narration clip lengths.

    python3 build.py <project> en          # writes index.html for the English track
    python3 build.py <project> hinglish    # rewrites index.html for Hinglish (render in between)

HyperFrames allows one root composition, so index.html always holds exactly one track.

Scene i lasts len(clip i) + pad (the last scene also + "outro_hold", default 3 s, for the subscribe
call-out). Each scene host gets data-variable-values {"T": <scene length>, "S": <narration length>} so
the scene file can time its tweens as fractions of T or S (same code for every language).
SFX cues: {"scene": id, "at": fraction of the scene's narration  |  "sec": seconds into the scene, "sound": name,
"volume": 0.35}; each sound is shifted so its loudest point lands one frame after the cue.
Also writes timing_<track>.json (scene starts/lengths) for insta.py.
"""
import argparse
import array
import json
import math
import os
import subprocess

from common import clip_path, duration, load_project, narration
from cues import clause_times

FPS = 30

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width={W}, height={H}" />
<title>{badge} – {title}</title>
<link rel="stylesheet" href="assets/lc.css" />
<link rel="stylesheet" href="assets/sd.css" />
{extra_css}
<script>window.LC_W = {W}; window.LC_H = {H};</script>
<script src="assets/lib/gsap.min.js"></script>
<script src="assets/lib/three.min.js"></script>
<script src="assets/lib/lc.js"></script>
<script src="assets/lib/sd3d.js"></script>
{scripts}<style>
  html, body {{ width: {W}px; height: {H}px; overflow: hidden; background: #0d1121; }}
  .lc-fill {{ width: {W}px; height: {H}px; }}
  #bg {{ position: absolute; inset: 0; background: radial-gradient(ellipse at 50% 40%, #151c36 0%, #0d1121 70%); }}
</style>
</head>
<body>
<!-- GENERATED by build.py from video.json – edit scenes in compositions/, timing in video.json -->
<div id="root" data-composition-id="main" data-start="0" data-duration="{total:.3f}" data-width="{W}" data-height="{H}">
  <div id="bg"></div>
"""

TAIL = """</div>
<script>
  window.__timelines = window.__timelines || {};
  window.__timelines["main"] = gsap.timeline({ paused: true });
</script>
</body>
</html>
"""


def peak_offset(path):
    """Seconds from the file start to its loudest sample (8 kHz mono analysis)."""
    raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", "8000",
                                   "-f", "s16le", "-"])
    a = array.array("h")
    a.frombytes(raw[: len(raw) // 2 * 2])
    if not a:
        return 0.0
    i = max(range(len(a)), key=lambda k: abs(a[k]))
    return i / 8000.0


def texts_for(project, track):
    return narration(project).get(track, [])


def caption_groups(words, max_chars=40, min_chars=24):
    """Group timed words [(start, end, word)] into readable caption chunks: break after a sentence end,
    or once a chunk is long enough (>= min_chars and on screen >= 0.5 s + 0.3 s/word), never past max_chars."""
    out, cur = [], []
    for k, w in enumerate(words):
        cur.append(w)
        text = " ".join(x[2] for x in cur)
        dur = cur[-1][1] - cur[0][0]
        nxt = words[k + 1][2] if k + 1 < len(words) else ""
        sentence_end = w[2][-1:] in ".!?।" and len(text) >= 10
        long_enough = len(text) >= min_chars and dur >= 0.5 + 0.3 * len(cur)
        too_long = len(text) + 1 + len(nxt) > max_chars
        if not nxt or sentence_end or long_enough or too_long:
            out.append((cur[0][0], cur[-1][1], text))
            cur = []
    return out


def write_captions(project, cfg, track, texts, clips, starts, speech, total, W, H):
    """Burned-in word-chunk captions (vertical videos): compositions/captions-<track>.html.
    Each clause starts where cues.py finds it (pause-snapped); its chunks split the clause's time by
    character share. Words listed in video.json "caption_highlight" are drawn in yellow."""
    import html as _html
    import re as _re
    cid = f"captions-{track}"
    hl = [h.lower() for h in cfg.get("caption_highlight", [])]
    ev = []
    for i, (text, clip) in enumerate(zip(texts, clips)):
        times = clause_times(clip, text)
        words = []
        for k, (t0, clause) in enumerate(times):
            t1 = times[k + 1][0] if k + 1 < len(times) else speech[i]
            ws = clause.split()
            tot = sum(len(w) + 1 for w in ws) or 1
            acc = 0
            for w in ws:
                a0 = t0 + (t1 - t0) * acc / tot
                acc += len(w) + 1
                words.append((starts[i] + a0, starts[i] + t0 + (t1 - t0) * acc / tot, w))
        ev += [(round(a, 3), round(b, 3), p) for a, b, p in caption_groups(words)]
    divs, tweens = [], []
    for n, (a, b, p) in enumerate(ev):
        words = []
        for w in p.split():
            core = _re.sub(r"[^\w\u0900-\u097F'-]", "", w).lower()
            e = _html.escape(w)
            words.append(f"<b>{e}</b>" if core and core in hl else e)
        divs.append(f'    <div class="v-cap" id="cap-{n}" data-layout-allow-overlap><span>{" ".join(words)}</span></div>')
        end = ev[n + 1][0] if n + 1 < len(ev) and ev[n + 1][0] - b < 0.6 else b + 0.3   # bridge short gaps
        tweens.append(f'      tl.fromTo("#cap-{n}", {{ opacity: 0, scale: 0.86, y: 18 }}, {{ opacity: 1, scale: 1, y: 0, duration: 0.16, ease: "back.out(2.5)" }}, {a});')
        tweens.append(f'      tl.set("#cap-{n}", {{ opacity: 0 }}, {max(a + 0.17, end - 0.01):.3f});')
    body = "\n".join(divs)
    js = "\n".join(tweens)
    page = f"""<template>
  <style>#root {{ position: absolute; inset: 0; pointer-events: none; }}</style>
  <div id="root" data-composition-id="{cid}" data-width="{W}" data-height="{H}">
{body}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
{js}
      tl.set({{}}, {{}}, {total});
      window.__timelines["{cid}"] = tl;
    }})();
  </script>
</template>
"""
    with open(os.path.join(project, "compositions", f"{cid}.html"), "w") as f:
        f.write(page)
    return cid


def build_track(project, cfg, track):
    t = cfg["tracks"][track]
    pad = cfg.get("pad", 0.6)
    scenes = cfg["scenes"]
    clips = [clip_path(project, t["audio"], i) for i in range(1, len(scenes) + 1)]
    if not all(clips):
        missing = [f"s{i}" for i, c in enumerate(clips, 1) if not c]
        print(f"[{track}] skipped – missing clips {missing} in {t['audio']}")
        return None
    lens = [round(duration(c) + pad, 3) for c in clips]
    hold = cfg.get("outro_hold", 3.0)          # extra seconds on the last slide for the subscribe call-out
    lens[-1] = round(lens[-1] + hold, 3)
    starts = [round(sum(lens[:i]), 3) for i in range(len(lens))]
    total = round(sum(lens), 3)
    pos = {sid: (starts[i], lens[i]) for i, sid in enumerate(scenes)}
    speech = [round(duration(c), 3) for c in clips]  # narration length per scene (variable "S")

    W, H = cfg.get("width", 1920), cfg.get("height", 1080)
    extra_css = "".join(f'<link rel="stylesheet" href="{c}" />\n' for c in cfg.get("styles", []))
    scripts = "".join(f'<script src="{s}"></script>\n' for s in cfg.get("scripts", []))
    html = [HEAD.format(badge=cfg.get("badge", "System Design"), title=cfg["title"], total=total, scripts=scripts,
                        W=W, H=H, extra_css=extra_css)]
    for i, sid in enumerate(scenes):
        s, T = pos[sid]
        html.append(
            f'  <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html"'
            f' data-start="{s}" data-duration="{T}" data-track-index="0" data-track-kind="graphics"'
            f' data-width="{W}" data-height="{H}" data-variable-values=\'{{"T":{T},"S":{speech[i]}}}\'></div>\n')
    for i, c in enumerate(clips):
        rel = os.path.relpath(c, project)
        html.append(f'  <audio id="vo-{track}-{i + 1}" class="clip" src="{rel}" data-start="{starts[i]}"'
                    f' data-duration="{math.floor((speech[i] - 0.06) * 100) / 100}" data-track-index="1" data-volume="1"></audio>\n')

    # sound effects, peak-aligned, greedy lanes from 2 upwards
    lanes_end = []
    peaks = {}
    for n, cue in enumerate(cfg.get("sfx", [])):
        if cue["scene"] not in pos:
            continue
        s, T = pos[cue["scene"]]
        sp = speech[scenes.index(cue["scene"])]
        at = s + (cue["sec"] if "sec" in cue else cue.get("at", 0) * sp)   # "at" = fraction of the narration
        f = os.path.join(project, "assets", "sfx", f"{cue['sound']}.mp3")
        if not os.path.exists(f):
            print(f"[{track}] sfx {cue['sound']} missing – run sfx.py")
            continue
        if f not in peaks:
            peaks[f] = (peak_offset(f), duration(f))
        pk, dur = peaks[f]
        start = max(0.0, round(at + 1 / FPS - pk, 3))
        lane = next((k for k, e in enumerate(lanes_end) if e <= start), None)
        if lane is None:
            lanes_end.append(0)
            lane = len(lanes_end) - 1
        lanes_end[lane] = start + dur
        html.append(f'  <audio id="sfx-{n + 1}" class="clip" src="assets/sfx/{cue["sound"]}.mp3"'
                    f' data-start="{start}" data-duration="{round(dur, 3)}" data-track-index="{2 + lane}"'
                    f' data-volume="{cue.get("volume", 0.35)}"></audio>\n')

    if cfg.get("captions"):
        cap_id = write_captions(project, cfg, track, texts_for(project, track), clips, starts, speech, total, W, H)
        html.append(f'  <div id="{cap_id}" data-composition-id="{cap_id}" data-composition-src="compositions/{cap_id}.html"'
                    f' data-start="0" data-duration="{total}" data-track-index="20" data-track-kind="graphics"'
                    f' data-width="{W}" data-height="{H}" style="z-index:50"></div>\n')

    music = cfg.get("music")
    if music:
        html.append(f'  <audio id="music" class="clip" src="{music["file"]}" data-start="0"'
                    f' data-duration="{total}" data-track-index="{2 + max(1, len(lanes_end))}"'
                    f' data-volume="{music.get("volume", 0.14)}" data-fade-in="1" data-fade-out="2"></audio>\n')
    html.append(TAIL)

    with open(os.path.join(project, "index.html"), "w") as f:
        f.write("".join(html))
    with open(os.path.join(project, f"timing_{track}.json"), "w") as f:
        json.dump({"scenes": [{"id": sid, "start": starts[i], "length": lens[i],
                               "speech": speech[i]} for i, sid in enumerate(scenes)],
                   "total": total}, f, indent=1)
    print(f"[{track}] index.html: {len(scenes)} scenes, {total:.1f}s -> render to {t['out']}")
    return total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("track", nargs="?", default="en")
    a = ap.parse_args()
    project, cfg = load_project(a.project)
    if build_track(project, cfg, a.track) is None:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
